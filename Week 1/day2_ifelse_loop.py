# If/Else — computer কে decision নিতে শেখাও
age = 37

if age >= 18:
    print("তুমি প্রাপ্তবয়স্ক")
else:
    print("তুমি নাবালক")

# আরেকটু complex
score = 85

if score >= 90:
    print("Grade: A+")
elif score >= 80:
    print("Grade: A")
elif score >= 70:
    print("Grade: B")
else:
    print("Grade: C")



# For Loop — নির্দিষ্ট বার কাজ করো
for day in range(1, 8):
    print("Week এর দিন নম্বর:", day)

# While Loop — শর্ত সত্য থাকলে চলতে থাকো
month = 1
while month <= 6:
    print("Month", month, "— শেখা চলছে!")
    month = month + 1





